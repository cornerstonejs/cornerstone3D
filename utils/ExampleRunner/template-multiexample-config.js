module.exports = function buildConfig(names, exampleBasePaths, destPath, root) {
  // Everything below is anchored to the repo root rather than the working
  // directory, so the generated config resolves the same no matter where the
  // generator or rspack itself is invoked from.
  const rootPath = root.replace(/\\/g, '/');
  const fromRoot = (...segments) => `${rootPath}/${segments.join('/')}`;

  const csRenderBasePath = fromRoot('packages/core/src/index');
  const csToolsBasePath = fromRoot('packages/tools/src/index');
  const csAiBasePath = fromRoot('packages/ai/src/index');
  const csLabelmapInterpolationBasePath = fromRoot(
    'packages/labelmap-interpolation/src/index'
  );
  const csPolymorphicSegmentationBasePath = fromRoot(
    'packages/polymorphic-segmentation/src/index'
  );
  const csAdaptersBasePath = fromRoot('packages/adapters/src/index');
  const csDICOMImageLoaderDistPath = fromRoot(
    'packages/dicomImageLoader/src/index'
  );
  const csMetadataBasePath = fromRoot('packages/metadata/src');
  const csUtilsBasePath = fromRoot('packages/utils/src');
  const csNiftiPath = fromRoot('packages/nifti-volume-loader/src/index');

  let multiExampleEntryPoints = '';

  names.forEach((name, index) => {
    const exampleBasePath = exampleBasePaths[index];
    multiExampleEntryPoints += `${name.replace(
      /\\/g,
      '/'
    )}: "${exampleBasePath.replace(/\\/g, '/')}", \n`;
  });

  let multiTemplates = '';
  names.forEach((name) => {
    multiTemplates += `
      new rspack.HtmlRspackPlugin({
        title: '${name}',
        chunks: ['${name}'],
        filename: '${name}.html',
        template: '${root.replace(
          /\\/g,
          '/'
        )}/utils/ExampleRunner/template.html',
      }),`;
  });

  multiTemplates += '\n';

  return `
// THIS FILE IS AUTOGENERATED - DO NOT EDIT
const fs = require('fs');
const rules = require('./rules-examples.js');
// The repo root's node_modules first, then the normal upward walk so nested
// (pnpm-style) package node_modules still resolve.
const modules = ['${rootPath}/node_modules', 'node_modules'];
const rspack = require('@rspack/core');

const dir = "${destPath.replace(/\\/g, '/')}";

if (!fs.existsSync(dir)){
    console.debug('Creating directory: ' + dir);
    fs.mkdirSync(dir);
}

module.exports = {
  mode: 'development',
  devtool: 'source-map',
  plugins: [
    ${multiTemplates}
    new rspack.DefinePlugin({
      __BASE_PATH__: "''",
    }),
    new rspack.CopyRspackPlugin({
      patterns: [
        {
          from: '${root.replace(/\\/g, '/')}/utils/ExampleRunner/serve.json',
          to: "${destPath.replace(/\\/g, '/')}"
        },
        {
          from: '${fromRoot(
            'node_modules/dicom-microscopy-viewer/dist/dynamic-import'
          )}',
          to: '${destPath.replace(/\\/g, '/') + '/dicom-microscopy-viewer/'}',
          noErrorOnMissing: true,
        },
        {
          from: '${fromRoot('node_modules/onnxruntime-web/dist')}',
          to: '${destPath.replace(/\\/g, '/')}/ort',
        },
      ],
    }),
    new rspack.ProvidePlugin({
      Buffer: ['buffer', 'Buffer'],
    }),
  ],
  entry: {
    ${multiExampleEntryPoints}
  },
  output: {
    path: '${destPath.replace(/\\/g, '/')}',
    filename: '[name].js',
  },
  module: {
    rules,
  },
  experiments: {
    asyncWebAssembly: true,
    nativeWatcher: true,
  },
  externals: {
    "dicom-microscopy-viewer": {
      root: "window",
      commonjs: "dicomMicroscopyViewer",
    },
  },
  resolve: {
    alias: {
      '@cornerstonejs/core': '${csRenderBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/tools': '${csToolsBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/ai': '${csAiBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/polymorphic-segmentation': '${csPolymorphicSegmentationBasePath.replace(
        /\\/g,
        '/'
      )}',
      '@cornerstonejs/labelmap-interpolation': '${csLabelmapInterpolationBasePath.replace(
        /\\/g,
        '/'
      )}',
      '@cornerstonejs/adapters': '${csAdaptersBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/metadata': '${csMetadataBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/utils': '${csUtilsBasePath.replace(/\\/g, '/')}',
      '@cornerstonejs/dicom-image-loader': '${csDICOMImageLoaderDistPath.replace(
        /\\/g,
        '/'
      )}',
      '@cornerstonejs/nifti-volume-loader': '${csNiftiPath.replace(
        /\\/g,
        '/'
      )}',
    },
    modules,
    extensions: ['.ts', '.tsx', '.js', '.jsx'],
    fallback: {
      fs: false,
      path: require.resolve('path-browserify'),
      events: false,
      buffer: require.resolve('buffer'),
      // vtk.js 36 pulls in xmlbuilder2@4 -> @oozcitak/url which requires
      // node's built-in 'url' module, unavailable in the browser bundle.
      url: false,
    },
  },
  devServer: {
    hot: true,
    open: false,
    port: ${process.env.CS3D_PORT || 3000},
    historyApiFallback: true,
    allowedHosts: [
      '127.0.0.1',
      'localhost',
    ],
  },
  optimization: {
    minimize: false,
    splitChunks: {
      chunks: 'all',
      cacheGroups: {
        defaultVendors: {
          test: /[\\/]node_modules[\\/]/,
          name: 'vendors',
          chunks: 'all',
        },
        commons: {
          test: /[\\/]packages[\\/]/,
          name: 'commons',
          chunks: 'all',
          minChunks: 2,
        },
      },
    }
  },
};
`;
};
