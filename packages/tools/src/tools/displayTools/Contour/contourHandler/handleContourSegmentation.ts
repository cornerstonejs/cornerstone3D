const cs3dLogger = cornerstoneUtilities.logger.toolsLog.getLogger(
  'tools.displayTools.Contour.contourHandler.handleContourSegmentation'
);

function handleContourSegmentation(
  viewport: Types.IViewport,
  geometryIds: string[],
  annotationUIDsMap: Map<number, Set<string>>,
  contourRepresentation: ContourRepresentation
) {
  if (annotationUIDsMap.size) {
    viewport.render();
  } else {
    addContourSetsToElement(viewport, geometryIds, contourRepresentation);
  }
}

function addContourSetsToElement(
  viewport: Types.IViewport,
  geometryIds: string[],
  contourRepresentation: ContourRepresentation
) {
  const { segmentationId } = contourRepresentation;

  const segmentSpecificMap = new Map();

  geometryIds.forEach((geometryId) => {
    const geometry = cache.getGeometry(geometryId);

    if (!geometry) {
      cs3dLogger.warn(
        `No geometry found for geometryId ${geometryId}. Skipping render.`
      );
      return;
    }

    const segmentIndex = (geometry.data as Types.IContourSet).segmentIndex;

    validateGeometry(geometry);

    const segmentSpecificConfig = segmentationStyle.getStyle({
      viewportId: viewport.id,
      segmentationId,
      type: SegmentationRepresentations.Contour,
      segmentIndex,
    });

    const contourSet = geometry.data as Types.IContourSet;
    const viewportNormal = getViewportICamera(viewport).viewPlaneNormal;

    contourSet.contours.forEach((contour) => {
      const { points, color, id } = contour;
      const viewPlaneNormal = getContourViewPlaneNormal(points, viewportNormal);

      const referencedImageId = getClosestImageIdForStackViewport(
        viewport as PlanarViewport,
        points[0],
        viewPlaneNormal
      );

      const contourSegmentationAnnotation = {
        annotationUID: utilities.uuidv4(),
        data: {
          contour: {
            closed: true,
            polyline: points,
          },
          segmentation: {
            segmentationId,
            segmentIndex,
            color,
            id,
          },
          handles: {},
        },
        handles: {},
        highlighted: false,
        autoGenerated: false,
        invalidated: false,
        isLocked: true,
        isVisible: true,
        metadata: {
          referencedImageId,
          toolName: 'PlanarFreehandContourSegmentationTool',
          FrameOfReferenceUID: viewport.getFrameOfReferenceUID(),
          viewPlaneNormal,
        },
      };
      const annotationGroupSelector = viewport.element;

      addAnnotation(contourSegmentationAnnotation, annotationGroupSelector);

      addContourSegmentationAnnotation(contourSegmentationAnnotation);
    });

    if (segmentSpecificConfig) {
      segmentSpecificMap.set(segmentIndex, segmentSpecificConfig);
    }
  });

  viewport.render();
}

/**
 * The view plane normal of the annotation of a contour: the normal of the
 * plane of its points, whichever viewport draws the contour set first. Its
 * sign follows the nearest of the axial, sagittal and coronal view plane
 * normals, and a contour that lies in one of those planes takes that normal
 * as it is, as it got when the viewport of that plane drew first. A contour
 * whose points span no plane takes the normal of the viewport.
 */
function getContourViewPlaneNormal(
  points: Types.Point3[],
  viewportNormal: Types.Point3
): Types.Point3 {
  const [x, y, z] = points.length >= 3 ? getNormal3(points) : [0, 0, 0];
  const normal: Types.Point3 = [x, y, z];

  if (!vec3.length(normal)) {
    return viewportNormal;
  }

  const nearest = ['axial', 'sagittal', 'coronal']
    .map(
      (orientation): Types.Point3 =>
        CONSTANTS.MPR_CAMERA_VALUES[orientation].viewPlaneNormal
    )
    .reduce((best, candidate) =>
      Math.abs(vec3.dot(candidate, normal)) > Math.abs(vec3.dot(best, normal))
        ? candidate
        : best
    );
  const alignment = vec3.dot(nearest, normal);

  if (Math.abs(alignment) > 1 - CONSTANTS.EPSILON) {
    return [...nearest] as Types.Point3;
  }

  return alignment < 0 ? [-x, -y, -z] : normal;
}

