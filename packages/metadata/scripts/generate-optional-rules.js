#!/usr/bin/env node
/* eslint-disable @typescript-eslint/no-require-imports */

/**
 * Writes `src/displayset/optionalDisplaySetRules.generated.ts` from the JSON
 * files in `rules/optional/`. The JSON files are the source: a server reads
 * them from the npm package, and the module gives the same data to code.
 *
 * Usage: node scripts/generate-optional-rules.js
 * The `prebuild` script runs it, and a unit test fails when the module and
 * the files differ.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const sourceDir = path.join(root, 'rules', 'optional');
const target = path.join(
  root,
  'src',
  'displayset',
  'optionalDisplaySetRules.generated.ts'
);

const files = {};
for (const name of fs.readdirSync(sourceDir).sort()) {
  if (name.endsWith('.json')) {
    const id = name.slice(0, -'.json'.length);
    files[id] = JSON.parse(fs.readFileSync(path.join(sourceDir, name), 'utf8'));
  }
}

const source =
  '// Generated by scripts/generate-optional-rules.js from rules/optional/*.json.\n' +
  '// Do not edit: change the JSON file, and run the script again.\n' +
  "import type { OptionalDisplaySetRuleFile } from './displaySetRulesTypes';\n\n" +
  'export const optionalDisplaySetRuleFiles: Record<string, OptionalDisplaySetRuleFile> = ' +
  JSON.stringify(files, null, 2) +
  ';\n';

async function main() {
  // The repository format, so that a commit hook does not change the file.
  const prettier = require('prettier');
  const options = (await prettier.resolveConfig(target)) ?? {};
  const text = await prettier.format(source, { ...options, filepath: target });
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) {
    fs.writeFileSync(target, text);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
